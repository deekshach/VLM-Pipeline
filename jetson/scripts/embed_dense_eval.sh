#!/bin/bash
# Dense ViT references for the main evaluation: every frame of each clip's pool encoded whole, native and
# window-aligned (jetson-embed-frames), as run_accuracy.sh built them for Sintel and MSVD. The pools are the
# Qwen-resolution ones of tools/accuracy/prepare_qres.py. The reference of tools/accuracy/vision_metrics.py: coverage
# of the whole clip, and the window cache's tokens against the same frame encoded whole. ViT only (no LLM), so the
# board guard can stay on.
#
#   bash jetson/scripts/embed_dense_eval.sh [datasets...]
#
# Results: /home/nvidia/data/accuracy/dense/<dataset>/<clip>/{native,aligned}/ (meta.json + frame_NNNN.f32). Clips
# whose pool is the same frames as another clip's (Perception Test questions on one video) link to its reference.
# Finished clips are skipped; a pool regenerated by prepare_qres.py needs its old reference moved aside first.
set -u
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$REPO/dmc955/model_config.sh"
ACC=/home/nvidia/data/accuracy
QRES="${QRES:-/mnt/external_ssd/VLM-datasets/qres}"
for DS in ${*:-sintel msvd charades nextqa videomme perception tacos}; do
    declare -A SEEN=()
    for C in "$QRES/pool/$DS/training/clean"/*; do
        V=$(basename "$C"); OUT=$ACC/dense/$DS/$V; R=$(realpath "$C")
        if [ -n "${SEEN[$R]:-}" ]; then   # the same frames under another clip name
            [ -e "$OUT" ] || ln -s "${SEEN[$R]}" "$OUT"
            continue
        fi
        SEEN[$R]=$V
        for MODE in native aligned; do
            [ -f "$OUT/$MODE/meta.json" ] && continue
            "$REPO/build/bin/jetson-embed-frames" "$MODEL" "$MMPROJ" "$R" "$OUT/$MODE" $MODE > /dev/null 2>&1 \
                || echo "FAIL $DS $V $MODE"
        done
        echo "$DS $V $(ls "$R" | wc -l) frames"
    done
    unset SEEN
done
